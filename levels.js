// =====================
// ДЕТЕРМИНИРОВАННЫЙ RANDOM (mulberry32)
// =====================
function seeded(seed) {
    let a = seed >>> 0;
    return function () {
        a |= 0; a = (a + 0x6D2B79F5) | 0;
        let t = Math.imul(a ^ (a >>> 15), 1 | a);
        t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

// =====================
// ТИРЫ / РАЗМЕРЫ
// =====================
function tierOf(roundIdx) {
    if (roundIdx < 40) return 1;
    if (roundIdx < 80) return 2;
    if (roundIdx < 160) return 3;
    if (roundIdx < 240) return 4;
    if (roundIdx < 280) return 5;
    return 6;
}

function sizeForTier(tier) {
    const sizes = { 1: 6, 2: 7, 3: 8, 4: 9, 5: 10, 6: 12 };
    return sizes[tier] || 6;
}

function wordsCountForTier(tier) {
    const counts = { 1: 3, 2: 4, 3: 5, 4: 6, 5: 7, 6: 8 };
    return counts[tier] || 3;
}

// =====================
// ВЫБОР СЛОВ
// =====================
function pickTheme(roundIdx, rand) {
    const themes = Object.keys(WORD_POOL);
    return themes[Math.floor(rand() * themes.length)];
}

function pickWordsFromPool(pool, count, rand, maxLen) {
    const filtered = pool.filter(w => w.length >= 4 && w.length <= maxLen);
    if (!filtered.length) return [];
    const result = [];
    const used = new Set();
    let guard = 0;
    while (result.length < count && guard < 200) {
        guard++;
        const w = filtered[Math.floor(rand() * filtered.length)];
        if (!used.has(w)) { used.add(w); result.push(w); }
    }
    return result;
}

function pickBonusWords(pool, count, rand, exclude) {
    const filtered = pool.filter(w => w.length >= 3 && w.length <= 10 && !exclude.has(w));
    const result = [];
    const used = new Set(exclude);
    let guard = 0;
    while (result.length < count && guard < 100) {
        guard++;
        const w = filtered[Math.floor(rand() * filtered.length)];
        if (w && !used.has(w)) { used.add(w); result.push(w); }
    }
    return result;
}

// =====================
// ГЕНЕРАТОР РАУНДА (41+)
// Змейка НЕ ставится принудительно. Только флаг snakeAvailable.
// =====================
function generateRound(roundIdx) {
    const tier = tierOf(roundIdx);
    const size = sizeForTier(tier);
    const count = wordsCountForTier(tier);
    const rand = seeded(roundIdx * 99991 + 12345);

    const themeName = pickTheme(roundIdx, rand);
    const themePool = WORD_POOL[themeName].map(normalizeWord);
    const globalPool = ALL_WORDS;

    // обычные слова (до 10 букв)
    let words = pickWordsFromPool(themePool.length >= count ? themePool : globalPool, count, rand, 10);
    if (words.length < count) {
        words = words.concat(pickWordsFromPool(globalPool, count - words.length, rand, 10));
    }

    // длинные слова — в отдельный пул (для сложного режима)
    const longPool = globalPool.filter(w => w.length >= 11 && w.length <= 20);
    let longWord = null;
    if (longPool.length) {
        longWord = longPool[Math.floor(rand() * longPool.length)];
    }

    const exclude = new Set(words);
    const bonusCount = 1 + (roundIdx % 3);
    const bonusWords = pickBonusWords(globalPool, bonusCount, rand, exclude);

    const reward = 10 + tier * 5;
    const golden = (roundIdx % 10 === 9);
    const items = ITEMS_BY_TIER[tier] || ITEMS_BY_TIER[1];
    const item = items[roundIdx % items.length] || items[0];

    // Сложный режим доступен с 41-го уровня
    const snakeAvailable = roundIdx >= 40;

    return {
        theme: themeName,
        size: size,
        words: words.map(w => w.toUpperCase()),
        snakeWords: 0,                    // всегда 0 — змейка по выбору
        snakeAvailable: snakeAvailable,    // флаг «можно выбрать сложный»
        longWord: longWord ? longWord.toUpperCase() : null, // для сложного
        bonusWords: bonusWords.map(w => w.toUpperCase()),
        item: item.ico,
        itemName: item.name,
        reward: reward,
        golden: golden,
        snake: false
    };
}

// =====================
// ГЛАВНАЯ ФУНКЦИЯ
// =====================
function getRound(roundIdx) {
    if (roundIdx < ROUNDS.length) {
        // ручные 1–40: добавляем snakeAvailable для 4-х уровней со snake:true
        const r = ROUNDS[roundIdx];
        return Object.assign({}, r, {
            snakeAvailable: !!r.snake,
            longWord: null,
            snakeWords: 0
        });
    }
    return generateRound(roundIdx);
}